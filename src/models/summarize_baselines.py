"""Turn results/baselines/metrics_*.csv into docs/BASELINE_RESULTS.md.

All headline tables use subset 'has_lag1' (rows where yesterday's AQI exists) so that persistence and
every model are scored on EXACTLY the same rows.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd

from paths import ROOT
from check_results import coverage_errors

RES = ROOT / "results" / "baselines"
SETS = ["S", "W", "SW", "SW+G", "SW+G+T", "SW+G+T+H"]
SUB = "has_lag1"


def md(df, floatfmt=1):
    df = df.copy()
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append("" if (isinstance(v, float) and np.isnan(v)) else (f"{v:.{floatfmt}f}" if isinstance(v, (float, np.floating)) else str(v)))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def load(p):
    f = RES / f"metrics_{p}.csv"
    if not f.exists():
        return None
    metrics = pd.read_csv(f)
    errors = coverage_errors(metrics, p)
    if errors:
        raise ValueError("Incomplete comparison: " + "; ".join(errors))
    return metrics


def overall(m, split):
    return m[(m.split == split) & (m.subset == SUB) & (m.level == "overall")]


def ladder_table(m, split, agg="mean"):
    o = overall(m, split)
    g = o.groupby(["feature_set", "model"]).agg(RMSE=("RMSE", agg), MAE=("MAE", agg), R2=("R2", agg)).reset_index()
    return g


def main():
    global RES, SETS
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results-dir", type=Path, default=RES)
    ap.add_argument("--output", type=Path)
    args = ap.parse_args()
    RES = args.results_dir.resolve()
    if not list(RES.glob("metrics_*.csv")):
        ap.error("No metrics files found in the results directory")
    manifest = None
    manifest_path = RES / "manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text())
        SETS = manifest["arguments"]["sets"]
    out = ["# Baseline results", "",
           "Auto-generated by `src/models/summarize_baselines.py` from `results/baselines/metrics_*.csv`. "
           f"Target: `AQI_eod`. Headline numbers are on rows where yesterday's AQI exists (subset `{SUB}`), so persistence and all "
           "models are scored on exactly the same rows. Hyper-parameters are fixed and untuned (same for every cell).", ""]

    if manifest:
        out += [f"Source run: `{RES}`. Status: {manifest['status']}. "
                + ("**Smoke test only; these are not full experiment results.**" if manifest["arguments"].get("quick") else ""), ""]

    # ------------------------------------------------------------ chronological
    m = load("chrono")
    if m is not None:
        out += ["## 1. Chronological split (train Jan-Aug, validate Sep-Oct, test Nov-Dec)", ""]
        ref = overall(m, "test")
        ref = ref[ref.feature_set == "-"][["model", "RMSE", "MAE", "R2"]]
        g = ladder_table(m, "test")
        g = g[g.feature_set != "-"]
        piv = g.pivot(index="model", columns="feature_set", values="RMSE")[SETS]
        out += ["**Test RMSE (AQI points) by feature set (columns) and model (rows)** -- lower is better", "",
                md(piv.reset_index()), "", "**Reference baselines (test)**", "", md(ref), ""]
        best = g.loc[g.groupby("feature_set").RMSE.idxmin()].set_index("feature_set").loc[SETS].reset_index()
        out += ["**Best model per ladder step (test)**", "", md(best), ""]
        piv2 = g.pivot(index="model", columns="feature_set", values="R2")[SETS]
        out += ["**Test R2**", "", md(piv2.reset_index(), 2), ""]

        # episodes / bands for the best model of two key steps
        out += ["**High-pollution days (test, true AQI >= 300): RMSE and bias** -- negative bias = under-prediction of extremes", ""]
        rows = []
        for fs in SETS:
            mm = m[(m.split == "test") & (m.subset == SUB) & (m.level == "episode") & (m.group == "AQI >= 300") & (m.feature_set == fs)]
            if mm.empty: continue
            b = mm.loc[mm.RMSE.idxmin()]
            rows.append({"feature_set": fs, "best model": b.model, "n": int(b.n), "RMSE": b.RMSE, "MAE": b.MAE, "bias": b.bias})
        out += [md(pd.DataFrame(rows)), ""]

        out += ["**Error by AQI band (test) for the best `SW+G+T` model: MAE and bias**", ""]
        b = best[best.feature_set == "SW+G+T"]
        if len(b):
            bm = b.iloc[0].model
            bb = m[(m.split == "test") & (m.subset == SUB) & (m.level == "band") & (m.feature_set == "SW+G+T") & (m.model == bm)][["group", "n", "MAE", "bias"]]
            out += [f"model: {bm}", "", md(bb.rename(columns={"group": "AQI band (true)"})), ""]

        # does the satellite help on days it is actually present?
        out += ["**Does satellite help when it is available?** Test RMSE on days with all 3 satellite bands (`sat_complete`), weather-only vs weather+satellite", ""]
        rows = []
        for model in sorted(m.model.unique()):
            if model in ("Persistence(yesterday)", "Climatology(city-month)"): continue
            r = {"model": model}
            for fs in ("W", "SW"):
                x = m[(m.split == "test") & (m.subset == "sat_complete") & (m.level == "overall") & (m.feature_set == fs) & (m.model == model)]
                r[f"{fs} RMSE"] = x.RMSE.iloc[0] if len(x) else np.nan
            r["gain from satellite"] = r["W RMSE"] - r["SW RMSE"]
            rows.append(r)
        out += [md(pd.DataFrame(rows)), ""]

    # ------------------------------------------------------------ leave-one-city-out
    m = load("loco")
    if m is not None:
        out += ["## 2. Leave-one-city-out (train on 7 cities, test on the held-out city; mean over the 8 held-out cities)", ""]
        g = ladder_table(m, "test")
        ref = g[g.feature_set == "-"][["model", "RMSE", "MAE", "R2"]]
        g = g[g.feature_set != "-"]
        out += ["**Mean test RMSE across held-out cities**", "", md(g.pivot(index="model", columns="feature_set", values="RMSE")[SETS].reset_index()), "",
                "**Mean test R2 across held-out cities**", "", md(g.pivot(index="model", columns="feature_set", values="R2")[SETS].reset_index(), 2), "",
                "**Reference baselines**", "", md(ref), ""]
        o = overall(m, "test")
        o = o[o.feature_set != "-"]
        o = o.assign(city=o.fold.str.replace("loco:", "", regex=False))
        best = o.loc[o.groupby(["city", "feature_set"]).RMSE.idxmin()]
        out += ["**Per held-out city: best-model RMSE by ladder step** (which cities transfer badly?)", "",
                md(best.pivot(index="city", columns="feature_set", values="RMSE")[SETS].reset_index()), ""]
        cl = overall(m, "test")
        cl = cl[cl.model == "Climatology(city-month)"].assign(city=lambda x: x.fold.str.replace("loco:", "", regex=False))[["city", "RMSE"]]
        out += ["Note: for an unseen city 'Climatology' can only use the month mean of the other cities.", ""]

    # ------------------------------------------------------------ season CV
    m = load("season_cv")
    if m is not None:
        out += ["## 3. Season-block folds (4 folds; each tests 3 interleaved months, trains on the rest)", ""]
        o = overall(m, "test")
        g = o.groupby(["feature_set", "model"]).agg(RMSE=("RMSE", "mean"), RMSE_sd=("RMSE", "std"), R2=("R2", "mean")).reset_index()
        ref = g[g.feature_set == "-"][["model", "RMSE", "RMSE_sd", "R2"]]
        g = g[g.feature_set != "-"]
        out += ["**Mean test RMSE across folds**", "", md(g.pivot(index="model", columns="feature_set", values="RMSE")[SETS].reset_index()), "",
                "**Fold-to-fold std of RMSE**", "", md(g.pivot(index="model", columns="feature_set", values="RMSE_sd")[SETS].reset_index()), "",
                "**Reference baselines**", "", md(ref), ""]

    (args.output or (ROOT / "docs" / "BASELINE_RESULTS.md" if RES == (ROOT / "results" / "baselines").resolve() else RES / "summary.md")).write_text("\n".join(out), encoding="utf-8")
    print("Summary written")


if __name__ == "__main__":
    main()
