"""results/sequence/metrics_*.csv (+ baselines) -> docs/SEQUENCE_RESULTS.md. Same headline subset as the baselines (has_lag1)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np
import pandas as pd

from paths import ROOT
from summarize_baselines import md

SUB = "has_lag1"
SEQ_SETS = ["SW-w1", "SW-w7", "SWT-w7"]
ENV_TAB = ["SW", "SW+G", "SW+G+T"]        # environment-only tabular rungs to compare against
PROTOCOLS = {"chrono": "Chronological (test Nov-Dec)", "loco": "Leave-one-city-out (mean of 8 held-out cities)",
             "season_cv": "Season-block CV (mean of 4 folds)"}


def overall(m, split="test"):
    return m[(m.split == split) & (m.subset == SUB) & (m.level == "overall")]


def agg(o):
    return o.groupby(["feature_set", "model"]).agg(RMSE=("RMSE", "mean"), MAE=("MAE", "mean"), R2=("R2", "mean")).reset_index()


def main():
    out = ["# Sequence-model results (environment-only GRU / LSTM)", "",
           "Auto-generated by `src/models/summarize_sequence.py`. Inputs are satellite + weather only -- **no AQI history**. "
           "`SW-w1` = today only (control without a temporal window), `SW-w7` = 7-day window, `SWT-w7` = 7-day window + day-of-year. "
           f"Each cell is the mean prediction of 3 seeds; hyper-parameters fixed/untuned. Scored on the same rows as the baselines (subset `{SUB}`).", ""]
    for p, title in PROTOCOLS.items():
        fs = ROOT / "results" / "sequence" / f"metrics_{p}.csv"
        fb = ROOT / "results" / "baselines" / f"metrics_{p}.csv"
        if not fs.exists() or not fb.exists():
            continue
        ms, mb = pd.read_csv(fs), pd.read_csv(fb)
        gs, gb = agg(overall(ms)), agg(overall(mb))
        rows = []
        for _, r in gs.iterrows():
            rows.append({"input set": r.feature_set, "model": r.model, "kind": "sequence", "RMSE": r.RMSE, "MAE": r.MAE, "R2": r.R2})
        for s in ENV_TAB:                                    # best tabular model of each environment-only rung
            x = gb[gb.feature_set == s]
            b = x.loc[x.RMSE.idxmin()]
            rows.append({"input set": s, "model": b.model, "kind": "best tabular", "RMSE": b.RMSE, "MAE": b.MAE, "R2": b.R2})
        for name in ("Persistence(yesterday)", "Climatology(city-month)"):
            x = gb[gb.model == name].iloc[0]
            rows.append({"input set": "-", "model": name, "kind": "reference", "RMSE": x.RMSE, "MAE": x.MAE, "R2": x.R2})
        t = pd.DataFrame(rows)
        out += [f"## {title}", "", md(t.rename(columns={"RMSE": "test RMSE", "MAE": "test MAE", "R2": "test R2"}), 2), ""]

        if p == "chrono":
            e = ms[(ms.split == "test") & (ms.subset == SUB) & (ms.level == "episode") & (ms.group == "AQI >= 300")]
            eb = mb[(mb.split == "test") & (mb.subset == SUB) & (mb.level == "episode") & (mb.group == "AQI >= 300") & mb.feature_set.isin(ENV_TAB)]
            bt = eb.loc[eb.RMSE.idxmin()]
            out += ["**Days with true AQI >= 300 (test)**: RMSE / bias (negative = under-prediction)", "",
                    md(pd.concat([e[["feature_set", "model", "n", "RMSE", "bias"]],
                                  pd.DataFrame([{"feature_set": bt.feature_set, "model": bt.model + " (best tabular)", "n": bt.n, "RMSE": bt.RMSE, "bias": bt.bias}])]), 1), ""]
        if p == "loco":
            o = overall(ms).assign(city=lambda x: x.fold.str.replace("loco:", "", regex=False))
            piv = o.pivot_table(index="city", columns=["feature_set", "model"], values="RMSE")
            piv.columns = [f"{a} {b}" for a, b in piv.columns]
            ob = overall(mb)
            ob = ob[ob.feature_set.isin(ENV_TAB)].assign(city=lambda x: x.fold.str.replace("loco:", "", regex=False))
            piv["best tabular env-only"] = ob.groupby("city").RMSE.min()
            pers = overall(mb)
            pers = pers[pers.model == "Persistence(yesterday)"].assign(city=lambda x: x.fold.str.replace("loco:", "", regex=False)).set_index("city")
            piv["persistence"] = pers.RMSE
            out += ["**Held-out-city RMSE**", "", md(piv.reset_index(), 1), ""]
    (ROOT / "docs" / "SEQUENCE_RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/SEQUENCE_RESULTS.md")


if __name__ == "__main__":
    main()
